const fs = require('node:fs')
const assert = require('node:assert/strict')
const main = fs.readFileSync('src/main/index.ts', 'utf8')
const preload = fs.readFileSync('src/preload/oauth.ts', 'utf8')
assert.ok(!main.includes('importChromeGoogleCookies'))
assert.ok(!main.includes("require('chrome-cookies-secure')"))
assert.ok(main.includes("getPreloadPath('oauth.js')"), 'Native popup uses inert preload instead of inheriting site bridge')
assert.ok(!main.includes('__oauthStub'))
assert.ok(!preload.includes('Object.defineProperty'))
assert.match(main, /if \(googlePopup/)
assert.match(main, /action: 'allow', overrideBrowserWindowOptions/)
const popup = main.slice(main.indexOf('const oauthWin = new BrowserWindow({'), main.indexOf('oauthWindows.add(oauthWin)'))
assert.match(popup, /session: ses/)
assert.match(popup, /contextIsolation: true/)
assert.match(popup, /nodeIntegration: false/)
assert.match(popup, /sandbox: true/)
assert.doesNotMatch(popup, /preload:/)
assert.ok(main.includes('routeOAuthCallback(oauthWin.webContents)'))
console.log('PASS: no Chrome-cookie import, no credentials override, isolated sandboxed popup, callback retained. Static checks only; no live login performed.')
